from __future__ import annotations

import functools
import json
import os
import threading
from dataclasses import dataclass, field
from typing import Any, Optional

from pydantic import BaseModel


@dataclass(frozen=True)
class Suggestions:
    best: str
    alternative: str  # Single longer/more complete alternative
    clarifying_question: Optional[str]
    technical_terms: list[dict[str, str]]  # List of {term, explanation}
    key_points: list[str] = field(default_factory=list)  # 3-5 short ideas to mention (not sentences)


class _TechTerm(BaseModel):
    term: str
    explanation: str


# Suggestions are generated by two parallel calls: a fast one (best + key points, shown first)
# and a fuller one (alternative, clarifying question, technical terms).
# Structured-output schemas sent to Gemini (response_schema). No docstring: it would be sent as the schema description.
class _QuickSchema(BaseModel):
    best: str
    key_points: list[str]


class _DetailsSchema(BaseModel):
    alternative: str
    clarifying_question: Optional[str]
    technical_terms: list[_TechTerm]


class _ClassifySchema(BaseModel):
    # Structured-output schema of the auto-answer classifier (no docstring, see above).
    is_question: bool


DEFAULT_MODEL = "gemini-3.6-flash"
# Small/fast model used by the auto-answer mode to confirm that OTHER expects an answer
DEFAULT_CLASSIFIER_MODEL = "gemini-3.5-flash-lite"
# Max number of key points kept from the model output
MAX_KEY_POINTS = 5
# Thinking level of the suggestions/chat calls (GEMINI_THINKING_LEVEL). Gemini 3.x can't turn
# thinking off; "low" roughly halves the latency of the model's default ("medium").
DEFAULT_THINKING_LEVEL = "low"
# The classifier only answers a yes/no question: the lowest level is enough
CLASSIFIER_THINKING_LEVEL = "minimal"
_THINKING_LEVELS = ("minimal", "low", "medium", "high")

# Lazily-created shared client (avoids per-call construction and reuses the HTTP pool)
_client: Any = None
# Calls run in parallel threads: without the lock, two first calls would each create a client
# and the discarded one closes its HTTP connection while still in use.
_client_lock = threading.Lock()


def _get_client():
    global _client
    with _client_lock:
        if _client is None:
            api_key = os.environ.get("GEMINI_API_KEY")
            if not api_key:
                raise RuntimeError("Missing env var: GEMINI_API_KEY")
            from google import genai  # type: ignore
            _client = genai.Client(api_key=api_key)
        return _client


def _model() -> str:
    return os.getenv("GEMINI_MODEL") or DEFAULT_MODEL


def _classifier_model() -> str:
    return os.getenv("GEMINI_CLASSIFIER_MODEL") or DEFAULT_CLASSIFIER_MODEL


@functools.lru_cache(maxsize=None)
def _valid_thinking_level(raw: str) -> Optional[str]:
    """Return the level if valid, else None (logged once per distinct value)."""
    level = raw.strip().lower()
    if level in _THINKING_LEVELS:
        return level
    print(f"[gemini] GEMINI_THINKING_LEVEL={raw!r} invalide (attendu: {'/'.join(_THINKING_LEVELS)}), ignoré")
    return None


def _thinking_config(level: Optional[str]) -> Any:
    """ThinkingConfig for `level`, or None (model default) when no valid level is given."""
    from google.genai import types  # type: ignore

    return types.ThinkingConfig(thinking_level=level.upper()) if level else None


def _suggestions_thinking() -> Any:
    return _thinking_config(_valid_thinking_level(os.getenv("GEMINI_THINKING_LEVEL") or DEFAULT_THINKING_LEVEL))


def _system_prompt(lang: str, profile: str = "") -> str:
    profile_section = ""
    if profile:
        if lang == "en":
            profile_section = (
                f"\n\n=== CANDIDATE PROFILE (ME) ===\n{profile}\n"
                "=== END PROFILE ===\n"
            )
        else:
            profile_section = (
                f"\n\n=== PROFIL DU CANDIDAT (ME) ===\n{profile}\n"
                "=== FIN PROFIL ===\n"
            )

    if lang == "en":
        base = (
            "You are a real-time interview assistant. You help ME reply to OTHER (recruiter/employer).\n"
            f"{profile_section}"
            "🚨 CRITICAL RULES 🚨\n\n"
            "1. ALWAYS ANSWER TECHNICAL QUESTIONS\n"
            "   - ME is intelligent and knowledgeable. NEVER say 'this is not my domain' or 'I'm not specialized in this'.\n"
            "   - If OTHER asks a technical question (algorithms, systems, theory), ANSWER IT correctly and confidently.\n"
            "   - ME knows computer science, AI/ML, systems, and can explain complex concepts.\n"
            "   - Connect the answer to the profile when relevant, but ALWAYS provide a real answer.\n\n"
            "2. NEVER LIE ABOUT PERSONAL EXPERIENCE\n"
            "   - Don't invent projects, achievements, or metrics that aren't in the profile.\n"
            "   - Don't say 'I reduced delays by X%' or 'I managed a team of X' unless it's IN THE PROFILE.\n"
            "   - Use ONLY real data from the profile provided above.\n\n"
            "3. DISTINCTION\n"
            "   - General knowledge (how does virtual memory work?) = ANSWER FULLY, ME knows this.\n"
            "   - Personal experience (what projects have you done?) = ONLY use facts from profile.\n\n"
            "Tone: confident, competent, professional. Help ME get the job.\n"
            "Do not mention you are an AI."
        )
    else:
        base = (
            "Tu es un assistant d'entretien en temps réel. Tu aides ME à répondre à OTHER (recruteur/employeur).\n"
            f"{profile_section}"
            "🚨 RÈGLES CRITIQUES 🚨\n\n"
            "1. TOUJOURS RÉPONDRE AUX QUESTIONS TECHNIQUES\n"
            "   - ME est intelligent et cultivé. JAMAIS dire 'ce n'est pas mon domaine' ou 'je ne suis pas spécialisé'.\n"
            "   - Si OTHER pose une question technique (algorithmes, systèmes, théorie), RÉPONDS correctement et avec confiance.\n"
            "   - ME connaît l'informatique, l'IA/ML, les systèmes, et peut expliquer des concepts complexes.\n"
            "   - Connecte la réponse au profil quand c'est pertinent, mais FOURNIS TOUJOURS une vraie réponse.\n\n"
            "2. JAMAIS MENTIR SUR L'EXPÉRIENCE PERSONNELLE\n"
            "   - N'invente pas de projets, réalisations ou métriques qui ne sont pas dans le profil.\n"
            "   - Ne dis pas 'j'ai réduit les délais de X%' ou 'j'ai géré une équipe de X' sauf si c'est DANS LE PROFIL.\n"
            "   - Utilise UNIQUEMENT les vraies données du profil fourni ci-dessus.\n\n"
            "3. DISTINCTION\n"
            "   - Connaissances générales (comment fonctionne la mémoire virtuelle?) = RÉPONDS COMPLÈTEMENT, ME sait ça.\n"
            "   - Expérience personnelle (quels projets as-tu faits?) = UNIQUEMENT les faits du profil.\n\n"
            "Ton: confiant, compétent, professionnel. Aide ME à décrocher le poste.\n"
            "Ne mentionne pas que tu es une IA."
        )
    return base


def _prompt_header(lang: str, transcript: str) -> str:
    """Transcript + focus instructions shared by the quick and details prompts."""
    if lang == "en":
        return (
            "Language: en\n"
            "Conversation transcript (oldest to newest):\n"
            f"{transcript}\n\n"
            "IMPORTANT: Focus on what OTHER (the interviewer/recruiter) just said or asked. "
            "Propose responses for ME (the candidate) to answer OTHER's questions or comments. "
            "Use what ME said before for context, but respond to OTHER.\n\n"
        )
    return (
        "Langue: fr\n"
        "Transcription de la conversation (du plus ancien au plus récent):\n"
        f"{transcript}\n\n"
        "IMPORTANT: Concentre-toi sur ce que OTHER (le recruteur/intervieweur) vient de dire ou demander. "
        "Propose des réponses pour ME (le candidat) pour répondre aux questions ou commentaires de OTHER. "
        "Utilise ce que ME a dit avant pour le contexte, mais réponds à OTHER.\n\n"
    )


def _quick_prompt(lang: str, transcript: str) -> str:
    """Fast call: best answer + key points."""
    if lang == "en":
        return _prompt_header(lang, transcript) + (
            "Tasks:\n"
            "1. Propose 1 BEST reply (concise, 2-3 sentences): the most natural and direct answer\n"
            "2. List 3 to 5 KEY POINTS for ME to mention: very short (2-8 words each), keywords or ideas, "
            "NOT ready-made sentences. Anything about ME's personal experience must come ONLY from the profile.\n\n"
            "Return STRICT JSON with keys:\n"
            "- best (string): concise best answer\n"
            "- key_points (array of strings): 3-5 very short key points (2-8 words each)"
        )
    return _prompt_header(lang, transcript) + (
        "Tâches:\n"
        "1. Propose 1 MEILLEURE réponse (concise, 2-3 phrases) : la réponse la plus naturelle et directe\n"
        "2. Liste 3 à 5 POINTS CLÉS à mentionner par ME : très courts (2 à 8 mots chacun), mots-clés ou idées, "
        "PAS des phrases toutes faites. Tout ce qui concerne l'expérience personnelle de ME doit venir UNIQUEMENT du profil.\n\n"
        "Retourne du JSON STRICT avec les clés:\n"
        "- best (string): meilleure réponse concise\n"
        "- key_points (array de strings): 3 à 5 points clés très courts (2 à 8 mots chacun)"
    )


def _details_prompt(lang: str, transcript: str) -> str:
    """Fuller call: longer alternative, clarifying question, technical terms."""
    if lang == "en":
        return _prompt_header(lang, transcript) + (
            "Tasks:\n"
            "1. Propose 1 ALTERNATIVE reply that is MORE COMPLETE and LONGER (4-6 sentences, more detailed): "
            "the developed version of the most natural and direct answer (same facts, same stance, more depth)\n"
            "2. If the question is ambiguous, propose a clarifying question\n"
            "3. Extract ONLY technical terms that are ACTUALLY WRITTEN in the transcript above. "
            "Do NOT invent terms. Only include words/acronyms that appear verbatim in the conversation "
            "(like MLOps, Kubernetes, RAG, CI/CD, Docker, etc.). If no technical terms appear, return empty array.\n\n"
            "Return STRICT JSON with keys:\n"
            "- alternative (string): longer, more detailed answer\n"
            "- clarifying_question (string|null)\n"
            "- technical_terms (array of objects with 'term' and 'explanation' - ONLY terms actually in the transcript)"
        )
    return _prompt_header(lang, transcript) + (
        "Tâches:\n"
        "1. Propose 1 réponse ALTERNATIVE plus COMPLÈTE et LONGUE (4-6 phrases, plus détaillée) : "
        "la version développée de la réponse la plus naturelle et directe (mêmes faits, même position, plus de profondeur)\n"
        "2. Si la question est ambiguë, propose une question de clarification\n"
        "3. Extrais UNIQUEMENT les termes techniques qui sont RÉELLEMENT ÉCRITS dans la transcription ci-dessus. "
        "N'invente PAS de termes. Inclus seulement les mots/acronymes qui apparaissent textuellement dans la conversation "
        "(comme MLOps, Kubernetes, RAG, CI/CD, Docker, etc.). Si aucun terme technique n'apparaît, retourne un tableau vide.\n\n"
        "Retourne du JSON STRICT avec les clés:\n"
        "- alternative (string): réponse plus longue et détaillée\n"
        "- clarifying_question (string|null)\n"
        "- technical_terms (array d'objets avec clés 'term' et 'explanation' - UNIQUEMENT les termes présents dans la transcription)"
    )


def _extract_json(text: str) -> dict[str, Any]:
    text = text.strip()
    try:
        return json.loads(text)
    except Exception:
        # crude fallback: grab first {...} block
        start = text.find("{")
        end = text.rfind("}")
        if start != -1 and end != -1 and end > start:
            return json.loads(text[start : end + 1])
        raise


def _normalize(obj: dict[str, Any]) -> Suggestions:
    best = str(obj.get("best") or "").strip()

    # Single alternative (longer/more complete)
    alternative = str(obj.get("alternative") or "").strip()

    # Clarifying question
    cq = obj.get("clarifying_question")
    cq_s = None
    if cq is not None:
        cq_s = str(cq).strip() or None

    # Technical terms explanations
    terms_raw = obj.get("technical_terms") or []
    if not isinstance(terms_raw, list):
        terms_raw = []
    technical_terms = []
    for t in terms_raw:
        if isinstance(t, dict):
            term = str(t.get("term") or "").strip()
            explanation = str(t.get("explanation") or "").strip()
            if term and explanation:
                technical_terms.append({"term": term, "explanation": explanation})

    # Key points: short strings, empties dropped, at most MAX_KEY_POINTS
    points_raw = obj.get("key_points") or []
    if not isinstance(points_raw, list):
        points_raw = []
    key_points = [p for p in (str(x).strip() for x in points_raw if x is not None) if p][:MAX_KEY_POINTS]

    return Suggestions(
        best=best,
        alternative=alternative,
        clarifying_question=cq_s,
        technical_terms=technical_terms,
        key_points=key_points,
    )


def _response_text_or_raise(resp: Any) -> str:
    """Return the response text, or raise with the block/finish reason if empty."""
    text = (resp.text or "").strip()
    if text:
        return text

    details = []
    feedback = resp.prompt_feedback
    if feedback is not None:
        if feedback.block_reason:
            details.append(f"block_reason={feedback.block_reason}")
        if feedback.block_reason_message:
            details.append(f"block_reason_message={feedback.block_reason_message}")
    if resp.candidates:
        candidate = resp.candidates[0]
        if candidate.finish_reason:
            details.append(f"finish_reason={candidate.finish_reason}")
        if candidate.finish_message:
            details.append(f"finish_message={candidate.finish_message}")
    else:
        details.append("no candidates")
    raise RuntimeError(f"Empty Gemini response ({', '.join(details)})")


def _response_to_dict(resp: Any, schema: type[BaseModel]) -> dict[str, Any]:
    """Structured output: prefer the SDK-validated `parsed`, else parse the raw text."""
    if isinstance(resp.parsed, schema):
        return resp.parsed.model_dump()
    return _extract_json(_response_text_or_raise(resp))


def generate_chat_response(*, lang: str, transcript: str, profile: str = "", question: str) -> str:
    """Answer a free-form question about the conversation."""
    from google.genai import types  # type: ignore

    client = _get_client()

    if lang == "en":
        system = (
            "You are a helpful interview assistant. You have access to the conversation transcript and the candidate's profile.\n"
            "Answer the user's question based on this context. Be concise and helpful.\n"
            "If the question is about strategy, give practical advice for the interview."
        )
        if profile:
            system += f"\n\n=== CANDIDATE PROFILE ===\n{profile}\n=== END PROFILE ==="
        user_msg = f"Conversation transcript:\n{transcript}\n\nQuestion: {question}"
    else:
        system = (
            "Tu es un assistant d'entretien. Tu as accès à la transcription de la conversation et au profil du candidat.\n"
            "Réponds à la question de l'utilisateur en te basant sur ce contexte. Sois concis et utile.\n"
            "Si la question concerne la stratégie, donne des conseils pratiques pour l'entretien."
        )
        if profile:
            system += f"\n\n=== PROFIL DU CANDIDAT ===\n{profile}\n=== FIN PROFIL ==="
        user_msg = f"Transcription de la conversation:\n{transcript}\n\nQuestion: {question}"

    resp = client.models.generate_content(
        model=_model(),
        contents=user_msg,
        config=types.GenerateContentConfig(
            system_instruction=system,
            temperature=0.4,
            thinking_config=_suggestions_thinking(),
        ),
    )

    return _response_text_or_raise(resp)


def _generate_structured(*, lang: str, transcript: str, profile: str, prompt: str,
                         schema: type[BaseModel]) -> Suggestions:
    """One structured suggestions call; fields absent from `schema` are left empty."""
    from google.genai import types  # type: ignore

    resp = _get_client().models.generate_content(
        model=_model(),
        contents=prompt,
        config=types.GenerateContentConfig(
            system_instruction=_system_prompt(lang, profile),
            temperature=0.3,
            response_mime_type="application/json",
            response_schema=schema,
            thinking_config=_suggestions_thinking(),
        ),
    )
    return _normalize(_response_to_dict(resp, schema))


def generate_quick_suggestions(*, lang: str, transcript: str, profile: str = "") -> Suggestions:
    """
    Synchronous (run via asyncio.to_thread). Fast call: only `best` and `key_points` are filled.
    Meant to run in parallel with generate_detailed_suggestions (same system instruction and transcript).
    """
    return _generate_structured(lang=lang, transcript=transcript, profile=profile,
                                prompt=_quick_prompt(lang, transcript), schema=_QuickSchema)


def generate_detailed_suggestions(*, lang: str, transcript: str, profile: str = "") -> Suggestions:
    """
    Synchronous (run via asyncio.to_thread). Fuller call: only `alternative`,
    `clarifying_question` and `technical_terms` are filled.
    """
    return _generate_structured(lang=lang, transcript=transcript, profile=profile,
                                prompt=_details_prompt(lang, transcript), schema=_DetailsSchema)


def combine_suggestions(quick: Optional[Suggestions], details: Optional[Suggestions]) -> Suggestions:
    """Merge the two partial results; a missing (failed) part leaves its fields empty."""
    return Suggestions(
        best=quick.best if quick else "",
        key_points=quick.key_points if quick else [],
        alternative=details.alternative if details else "",
        clarifying_question=details.clarifying_question if details else None,
        technical_terms=details.technical_terms if details else [],
    )


def _classify_prompts(lang: str, transcript: str, utterance: str) -> tuple[str, str]:
    """Return (system, user) prompts for classify_question."""
    if lang == "en":
        system = (
            "You classify utterances in a live job interview between ME (the candidate) and OTHER "
            "(recruiter/interviewer). Decide whether OTHER's latest utterance expects an answer from ME "
            "right now: a question, a request to describe/explain/tell something, or an interview prompt. "
            "Small talk, statements, acknowledgements ('ok', 'great'), OTHER presenting the company, "
            "rhetorical or unfinished sentences, or questions addressed to someone else are NOT. "
            'Reply with JSON {"is_question": true|false}.'
        )
        user = (
            f"Recent conversation (oldest to newest):\n{transcript}\n\n"
            f"OTHER's latest utterance:\n{utterance}"
        )
    else:
        system = (
            "Tu classes les prises de parole d'un entretien d'embauche en direct entre ME (le candidat) et OTHER "
            "(recruteur/intervieweur). Décide si la dernière prise de parole de OTHER attend une réponse de ME "
            "maintenant : une question, une demande de décrire/expliquer/raconter quelque chose, ou une consigne "
            "d'entretien. Les banalités, affirmations, acquiescements ('ok', 'très bien'), présentations de "
            "l'entreprise par OTHER, phrases rhétoriques ou inachevées, ou questions adressées à quelqu'un d'autre "
            'n\'en sont PAS. Réponds en JSON {"is_question": true|false}.'
        )
        user = (
            f"Conversation récente (du plus ancien au plus récent):\n{transcript}\n\n"
            f"Dernière prise de parole de OTHER:\n{utterance}"
        )
    return system, user


def classify_question(*, lang: str, transcript: str, utterance: str) -> bool:
    """
    Synchronous (run via asyncio.to_thread). True if OTHER's latest utterance expects an answer
    from ME right now; `transcript` is the recent context (~15 lines). Never raises: on any
    error it logs and returns False (the auto-answer mode must not spam errors).
    """
    try:
        from google.genai import types  # type: ignore

        system, user = _classify_prompts(lang, transcript, utterance)
        resp = _get_client().models.generate_content(
            model=_classifier_model(),
            contents=user,
            config=types.GenerateContentConfig(
                system_instruction=system,
                temperature=0,
                response_mime_type="application/json",
                response_schema=_ClassifySchema,
                thinking_config=_thinking_config(CLASSIFIER_THINKING_LEVEL),
            ),
        )
        if isinstance(resp.parsed, _ClassifySchema):
            return resp.parsed.is_question
        return _extract_json(_response_text_or_raise(resp)).get("is_question") is True
    except Exception as e:
        print(f"[auto-answer] classification failed: {e!r}")
        return False
